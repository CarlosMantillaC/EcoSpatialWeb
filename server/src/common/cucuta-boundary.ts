/** true si el punto esta dentro del perimetro urbano de Cucuta. */
export function isInsideCucuta(point: Coords): boolean {
  return pointInRing(CUCUTA_BOUNDARY, point);
}

/**
 * true si TODA la geometria de una ruta (LineString [lng, lat]) se
 * mantiene dentro del perimetro urbano de Cucuta. Geometria vacia o
 * nula se considera valida (no hay evidencia de que salga).
 */
export function isRouteInsideCucuta(
  geometry: LineStringCoords | { coordinates?: LineStringCoords | null } | null | undefined,
): boolean {
  const coords = toLineStringCoords(geometry as LineStringCoords | null);
  if (!coords || coords.length === 0) return true;
  return coords.every(([lng, lat]) => isInsideCucuta({ lat, lng }));
}

/** Point-in-polygon por ray casting sobre un anillo [lng, lat]. */
function pointInRing(ring: LineStringCoords, point: Coords): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const intersects =
      yi > point.lat !== yj > point.lat &&
      point.lng < ((xj - xi) * (point.lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}
